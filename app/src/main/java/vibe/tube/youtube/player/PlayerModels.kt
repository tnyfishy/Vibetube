package vibe.tube.youtube.player

import vibe.tube.core.PlaybackFailure

data class StreamFormat(
    val itag: Int,
    val url: String,
    val mimeType: String,
    val codecs: String?,
    val bitrate: Int,
    val width: Int?,
    val height: Int?,
    val fps: Int?,
    val qualityLabel: String?,
    val audioTrackId: String?,
    val audioTrackName: String?,
    val isDefaultAudio: Boolean,
    val contentLength: Long?,
                                                                                         
    val audioQuality: String? = null,
    val audioSampleRate: Int? = null,
    val audioChannels: Int? = null,
                                                                                                              
    val isDrc: Boolean = false,
) {
    val isVideo: Boolean get() = mimeType.startsWith("video/")
    val isAudio: Boolean get() = mimeType.startsWith("audio/")
    val isMp4Family: Boolean get() = mimeType.contains("mp4")
    val isAvc: Boolean get() = codecs?.startsWith("avc1") == true
    val isAac: Boolean get() = codecs?.startsWith("mp4a") == true
    val isOpus: Boolean get() = codecs?.startsWith("opus") == true

    val audioTier: Int get() = when (audioQuality) {
        "AUDIO_QUALITY_HIGH" -> 3
        "AUDIO_QUALITY_MEDIUM" -> 2
        "AUDIO_QUALITY_LOW", "AUDIO_QUALITY_ULTRALOW" -> 1
        else -> 0
    }
}

data class CaptionTrack(
    val languageCode: String,
    val name: String,
    val url: String,
    val isAutoGenerated: Boolean,
                                                                                                  
    val isTranslatable: Boolean = false,
                                                                                                                      
    val isTranslation: Boolean = false,
) {
                                                                                                                           
    val id: String get() = languageCode + (if (isAutoGenerated && !isTranslation) ":asr" else "") + (if (isTranslation) ":tl" else "")
}

data class ResolvedMedia(
    val videoId: String,
    val title: String?,
    val author: String?,
    val durationSeconds: Long?,
    val isLive: Boolean,
    val hlsUrl: String?,
    val muxed: List<StreamFormat>,
    val videoOnly: List<StreamFormat>,
    val audioOnly: List<StreamFormat>,
    val captions: List<CaptionTrack>,
                                                                           
    val captionTranslations: List<String> = emptyList(),
    val expiresAtMillis: Long?,
    val clientName: String,
    val userAgent: String,
    val skippedCipherFormats: Int,
                                                                                                                 
    val publishedAt: String? = null,
    val loudnessDb: Double? = null,
    /** A DASH manifest, served for live broadcasts by some clients next to the HLS one. */
    val dashUrl: String? = null,
    /** A SABR-capable answer for the same video, kept so the format pair is chosen against the quality cap. */
    val sabr: vibe.tube.player.sabr.integration.SabrOffer? = null,
)

sealed interface ResolveResult {
    data class Playable(val media: ResolvedMedia) : ResolveResult
    data class Blocked(val failure: PlaybackFailure, val detail: String?, val clientName: String, val scheduledStartMs: Long? = null) : ResolveResult
}

enum class PlanKind { Adaptive, Muxed, Hls, Dash, Sabr }

data class MediaPlan(
    val kind: PlanKind,
    val video: StreamFormat?,
    val audio: StreamFormat?,
    val muxed: StreamFormat?,
    val hlsUrl: String?,
    val height: Int?,
    val dashUrl: String? = null,
    val sabr: vibe.tube.player.sabr.integration.SabrStreamInfo? = null,
)

data class AudioTrackOption(val id: String, val name: String, val isDefault: Boolean)
