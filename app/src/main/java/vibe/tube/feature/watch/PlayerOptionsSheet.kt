package vibe.tube.feature.watch

import androidx.compose.foundation.layout.Arrangement
import androidx.compose.foundation.layout.Column
import androidx.compose.foundation.layout.fillMaxWidth
import kotlin.math.roundToInt
import androidx.compose.foundation.layout.navigationBarsPadding
import androidx.compose.foundation.layout.padding
import androidx.compose.foundation.rememberScrollState
import androidx.compose.foundation.verticalScroll
import androidx.compose.material3.ExperimentalMaterial3Api
import androidx.compose.material3.FilterChip
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.ModalBottomSheet
import androidx.compose.material3.Text
import androidx.compose.runtime.Composable
import androidx.compose.foundation.layout.Row
import androidx.compose.material3.Slider
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier
import androidx.compose.ui.res.stringResource
import vibe.tube.R
import vibe.tube.player.PlayerController
import vibe.tube.player.PlayerUiState
import vibe.tube.ui.theme.Spacing

private val speeds = listOf(0.5f, 0.75f, 1f, 1.25f, 1.5f, 2f)

@OptIn(ExperimentalMaterial3Api::class, androidx.compose.foundation.layout.ExperimentalLayoutApi::class)
@Composable
fun PlayerOptionsSheet(state: PlayerUiState, controller: PlayerController, onDismiss: () -> Unit) {
    ModalBottomSheet(onDismissRequest = onDismiss) {
        Column(
            Modifier.navigationBarsPadding().verticalScroll(rememberScrollState()).padding(horizontal = Spacing.lg, vertical = Spacing.sm),
            verticalArrangement = Arrangement.spacedBy(Spacing.md),
        ) {
            Text(stringResource(R.string.player_options), style = MaterialTheme.typography.titleLarge)

            Section(R.string.player_speed) {
                speeds.forEach { value ->
                    FilterChip(
                        selected = state.speed == value,
                        onClick = { controller.setSpeed(value) },
                        label = { Text(if (value == 1f) stringResource(R.string.player_speed_normal) else "${value}x") },
                    )
                }
            }
            TuningSlider(stringResource(R.string.player_speed), state.speed, 0.25f..3f, controller::setSpeed)
            TuningSlider(stringResource(R.string.player_pitch), state.pitch, 0.5f..2f, controller::setPitch)
            Row(verticalAlignment = Alignment.CenterVertically, horizontalArrangement = Arrangement.spacedBy(Spacing.sm)) {
                FilterChip(
                    selected = state.tuningRemembered,
                    onClick = { controller.setRememberTuning(!state.tuningRemembered) },
                    label = { Text(stringResource(R.string.player_tuning_remember)) },
                )
                androidx.compose.material3.OutlinedButton(onClick = { controller.setSpeed(1f); controller.setPitch(1f) }) {
                    Text(stringResource(R.string.player_tuning_reset))
                }
            }
            if (state.qualities.isNotEmpty()) {
                Section(R.string.player_quality) {
                    FilterChip(
                        selected = state.selectedHeight == null,
                        onClick = { controller.selectQuality(null) },
                        label = {
                            Text(
                                if (state.selectedHeight == null && state.activeHeight != null) {
                                    stringResource(R.string.quality_auto_active, state.activeHeight)
                                } else stringResource(R.string.quality_auto),
                            )
                        },
                    )
                    state.qualities.forEach { h ->
                        FilterChip(
                            selected = state.selectedHeight == h,
                            onClick = { controller.selectQuality(h) },
                            label = { Text("${h}p") },
                        )
                    }
                }
            }
            if (state.captions.isNotEmpty()) {
                Section(R.string.player_captions) {
                    FilterChip(
                        selected = state.selectedCaption == null,
                        onClick = { controller.selectCaption(null) },
                        label = { Text(stringResource(R.string.player_captions_off)) },
                    )
                    state.captions.forEach { track ->
                        FilterChip(
                            selected = state.selectedCaption == track.languageCode,
                            onClick = { controller.selectCaption(track.languageCode) },
                            label = { Text(if (track.isAutoGenerated) stringResource(R.string.player_caption_auto, track.name) else track.name) },
                        )
                    }
                }
            }
            if (state.audioTracks.size > 1) {
                Section(R.string.player_audio_tracks) {
                    state.audioTracks.forEach { track ->
                        FilterChip(
                            selected = state.selectedAudioTrack == track.id || (state.selectedAudioTrack == null && track.isDefault),
                            onClick = { controller.selectAudioTrack(track.id) },
                            label = { Text(track.name) },
                        )
                    }
                }
            }
            state.clientName?.let {
                Text(
                    stringResource(R.string.player_source_note),
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                )
            }
        }
    }
}

@OptIn(androidx.compose.foundation.layout.ExperimentalLayoutApi::class)
@Composable
private fun Section(title: Int, content: @Composable androidx.compose.foundation.layout.FlowRowScope.() -> Unit) {
    Column(verticalArrangement = Arrangement.spacedBy(Spacing.sm)) {
        Text(stringResource(title), style = MaterialTheme.typography.titleSmall)
        androidx.compose.foundation.layout.FlowRow(
            horizontalArrangement = Arrangement.spacedBy(Spacing.sm),
            verticalArrangement = Arrangement.spacedBy(Spacing.xs),
            content = content,
        )
    }
}

@Composable
private fun TuningSlider(label: String, value: Float, range: ClosedFloatingPointRange<Float>, onChange: (Float) -> Unit) {
    Column {
        Row(Modifier.fillMaxWidth(), horizontalArrangement = Arrangement.SpaceBetween) {
            Text(label, style = MaterialTheme.typography.titleSmall)
            Text(String.format(java.util.Locale.US, "%.2fx", value), style = MaterialTheme.typography.labelLarge, color = MaterialTheme.colorScheme.primary)
        }
        Slider(
            value = value,
            onValueChange = { onChange((it * 20f).roundToInt() / 20f) },
            valueRange = range,
        )
    }
}
