#!/usr/bin/env python3
"""
Regenerates Vibetube's icon drawables from the official Material Symbols Rounded variable font.

    python3 -I tools/icons/generate_symbols.py <MaterialSymbolsRounded[FILL,GRAD,opsz,wght].ttf> <matching .codepoints>

Font and codepoints: https://github.com/google/material-design-icons/tree/master/variablefont (Apache-2.0).
Requires fontTools (pip install fonttools).

Every icon is drawn at Weight 400, Grade 100, Optical size 28 (tools/icons/symbols.txt lists the names and fills).
Outlines come straight from the font at that location, written as absolute M/L/Q/Z commands only.

FILL works like the font itself: between 0 and 0.99 the outline glyph's own gvar deltas sweep the fill in, and from
0.99 the font substitutes a separate, clean filled glyph (its FeatureVariations / rvrn rule), because the swept outline
at FILL 1 still has hairline counters left. So for every `ic_x_filled`:
  - `ic_x_filled.xml` is that clean substitute glyph (what a selected icon shows at rest), and
  - `ic_x_filled_morph.xml` is the outline glyph at FILL 1, point-for-point compatible with `ic_x.xml`,
which vibe.tube.ui.components.MorphingSymbol interpolates and then hands over to the clean glyph at the end.
"""
import os
import sys

from fontTools.pens.basePen import BasePen
from fontTools.ttLib import TTFont

AXES = {"wght": 400, "GRAD": 100, "opsz": 28}
HERE = os.path.dirname(os.path.abspath(__file__))
DRAWABLES = os.path.join(HERE, "..", "..", "app", "src", "main", "res", "drawable")


class PathWriter(BasePen):
    """SVG path in VectorDrawable coordinates (y down, glyph baseline at 0, see translateY in the XML)."""

    def __init__(self, glyph_set):
        super().__init__(glyph_set)
        self.parts = []

    @staticmethod
    def n(v):
        s = f"{v:.2f}".rstrip("0").rstrip(".")
        return "0" if s in ("-0", "") else s

    def p(self, pt):
        return f"{self.n(pt[0])},{self.n(-pt[1])}"

    def _moveTo(self, pt):
        self.parts.append("M" + self.p(pt))

    def _lineTo(self, pt):
        self.parts.append("L" + self.p(pt))

    def _qCurveToOne(self, pt1, pt2):
        self.parts.append("Q" + self.p(pt1) + " " + self.p(pt2))

    def _curveToOne(self, pt1, pt2, pt3):
        self.parts.append("C" + self.p(pt1) + " " + self.p(pt2) + " " + self.p(pt3))

    def _closePath(self):
        self.parts.append("Z")

    def text(self):
        return "".join(self.parts)


XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Material Symbols Rounded "{name}", FILL {fill} wght 400 GRAD 100 opsz 28{note}. Generated by tools/icons/generate_symbols.py; do not edit. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="24dp"
    android:height="24dp"
    android:viewportWidth="960"
    android:viewportHeight="960">
  <group android:translateY="960">
    <path
        android:fillColor="@android:color/white"
        android:pathData="{path}"/>
  </group>
</vector>
"""


def main(font_path, codepoints_path):
    names = set()
    with open(codepoints_path) as f:
        for line in f:
            if line.strip():
                names.add(line.split()[0])
    font = TTFont(font_path)
    cmap = font.getBestCmap()
    codepoints = {}
    with open(codepoints_path) as f:
        for line in f:
            if line.strip():
                n, cp = line.split()
                codepoints[n] = int(cp, 16)
    sets = {fill: font.getGlyphSet(location={**AXES, "FILL": fill}) for fill in (0, 1)}
    # The font's own FILL >= 0.99 substitution (base glyph -> clean filled glyph).
    clean = {}
    gsub = font["GSUB"].table
    for record in gsub.FeatureVariations.FeatureVariationRecord:
        for sub in record.FeatureTableSubstitution.SubstitutionRecord:
            for index in sub.Feature.LookupListIndex:
                for table in gsub.LookupList.Lookup[index].SubTable:
                    clean.update(getattr(table, "mapping", {}) or {})
    entries = []
    with open(os.path.join(HERE, "symbols.txt")) as f:
        for line in f:
            line = line.split("#")[0].strip()
            if line:
                drawable, symbol, fill = line.split()
                entries.append((drawable, symbol, int(fill)))
    for drawable, symbol, fill in entries:
        if symbol not in names:
            sys.exit(f"{drawable}: '{symbol}' is not a Material Symbols name")
        glyph = cmap.get(codepoints[symbol])
        if glyph is None:
            sys.exit(f"{drawable}: the font has no glyph for '{symbol}'")
        def write(name, glyph_name, note):
            pen = PathWriter(sets[fill])
            sets[fill][glyph_name].draw(pen)
            with open(os.path.join(DRAWABLES, name + ".xml"), "w") as out:
                out.write(XML.format(name=symbol, fill=fill, note=note, path=pen.text()))
        if fill == 1:
            write(drawable, clean.get(glyph, glyph), "")
            if drawable.endswith("_filled") and drawable[: -len("_filled")] in {e[0] for e in entries}:
                write(drawable + "_morph", glyph, " (morph target: outline glyph at FILL 1, for animation only)")
        else:
            write(drawable, glyph, "")
    # Outline / filled pairs must be morphable: same commands in the same order.
    by_name = {d: (s, fl) for d, s, fl in entries}
    for d in by_name:
        if d.endswith("_filled") and d[: -len("_filled")] in by_name:
            d = d + "_morph"
            def commands(name):
                with open(os.path.join(DRAWABLES, name + ".xml")) as f:
                    data = f.read().split('pathData="')[1].split('"')[0]
                return "".join(c for c in data if c.isalpha())
            if commands(d) != commands(d[: -len("_filled_morph")]):
                sys.exit(f"{d}: not point-compatible with its outline")
    print(f"wrote {len(entries)} drawables")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
